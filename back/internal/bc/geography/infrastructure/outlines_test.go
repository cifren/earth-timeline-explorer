func TestLoadOutlinesHasEveryZone(t *testing.T) {
	outlines, err := LoadOutlines()
	if err != nil {
		t.Fatal(err)
	}
	if len(outlines.Zones) != len(zoning.All()) {
		t.Fatalf("loaded %d outlines, want %d", len(outlines.Zones), len(zoning.All()))
	}
	for _, outline := range outlines.Zones {
		if len(outline.Polygons) == 0 {
			t.Errorf("zone %s has no polygon", outline.Zone.ID)
		}
	}
	if !strings.HasPrefix(outlines.ETag, `"`) || !strings.HasSuffix(outlines.ETag, `"`) {
		t.Fatalf("ETag %s is not a quoted entity tag", outlines.ETag)
	}
}

func TestWriteOutlinesGeneratesAGoPackage(t *testing.T) {
	europe, _ := zoning.Find(zoning.Europe)
	square := domain.Polygon{domain.Ring{{0, 0}, {1, 0}, {1, 1}, {0, 1}, {0, 0}}}
	path := filepath.Join(t.TempDir(), "geozone", "zones.gen.go")

	if err := WriteOutlines(path, []domain.Outline{{Zone: europe, Polygons: []domain.Polygon{square}}}); err != nil {
		t.Fatal(err)
	}

	source, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	text := string(source)
	if !strings.HasPrefix(text, "// Code generated by cmd/zones") || !strings.Contains(text, "package geozone") {
		t.Fatalf("generated file lacks its header or package:\n%s", text[:min(len(text), 200)])
	}
	start := strings.Index(text, "`")
	end := strings.LastIndex(text, "`")
	var collection featureCollection
	if err := json.Unmarshal([]byte(text[start+1:end]), &collection); err != nil {
		t.Fatalf("generated GeoJSON does not decode: %v", err)
	}
	if len(collection.Features) != 1 || collection.Features[0].Properties.ID != zoning.Europe {
		t.Fatalf("generated features = %+v", collection.Features)
	}
}

func TestWriteCountryPointsGeneratesAGoPackage(t *testing.T) {
	path := filepath.Join(t.TempDir(), "geozone", "countries.gen.go")

	if err := WriteCountryPoints(path, map[string][2]float64{"Denmark": {9.018163, 55.966965}, "Chile": {-72.3, -38.1}}); err != nil {
		t.Fatal(err)
	}

	source, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	text := string(source)
	for _, want := range []string{"// Code generated by cmd/zones", "package geozone", `"Chile":   {-72.3, -38.1},`, `"Denmark": {9.018163, 55.966965},`} {
		if !strings.Contains(text, want) {
			t.Fatalf("generated file lacks %q:\n%s", want, text)
		}
	}
}
