// Package infrastructure reads and writes the zone outlines. The zones command writes
// them as a generated Go package, so that they are compiled into the binary.
package infrastructure

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"

	"frise-chrono/back/internal/bc/geography/domain"
	"frise-chrono/back/internal/core/zoning"
	"frise-chrono/back/var/geozone"
)

// OutlinesFile is the path, relative to the back module, of the generated outlines.
const OutlinesFile = "var/geozone/zones.gen.go"

const generatedSource = `// Code generated by cmd/zones from Natural Earth. DO NOT EDIT.

// Package geozone holds geographic outlines.
package geozone

// Zones is a GeoJSON FeatureCollection (RFC 7946) with one MultiPolygon per zone.
const Zones = %s
`

type featureCollection struct {
	Features []struct {
		Properties struct {
			ID zoning.ID `json:"id"`
		} `json:"properties"`
		Geometry struct {
			Coordinates []domain.Polygon `json:"coordinates"`
		} `json:"geometry"`
	} `json:"features"`
}

// Outlines are the zone shapes embedded in the binary, with their entity tag.
type Outlines struct {
	Zones []domain.Outline
	ETag  string
}

// LoadOutlines decodes the generated outlines once, at startup.
func LoadOutlines() (Outlines, error) {
	var collection featureCollection
	if err := json.Unmarshal([]byte(geozone.Zones), &collection); err != nil {
		return Outlines{}, fmt.Errorf("decode zone outlines: %w", err)
	}
	outlines := make([]domain.Outline, 0, len(collection.Features))
	for _, feature := range collection.Features {
		zone, known := zoning.Find(feature.Properties.ID)
		if !known {
			return Outlines{}, fmt.Errorf("decode zone outlines: unknown zone %q", feature.Properties.ID)
		}
		outlines = append(outlines, domain.Outline{Zone: zone, Polygons: feature.Geometry.Coordinates})
	}
	sum := sha256.Sum256([]byte(geozone.Zones))
	return Outlines{Zones: outlines, ETag: `"` + hex.EncodeToString(sum[:8]) + `"`}, nil
}

type outputFeature struct {
	Type       string `json:"type"`
	Properties struct {
		ID   zoning.ID `json:"id"`
		Name string    `json:"name"`
	} `json:"properties"`
	Geometry struct {
		Type        string           `json:"type"`
		Coordinates []domain.Polygon `json:"coordinates"`
	} `json:"geometry"`
}

// WriteOutlines saves the outlines as a GeoJSON FeatureCollection (RFC 7946), one
// MultiPolygon feature per zone, inside the generated Go package.
func WriteOutlines(path string, outlines []domain.Outline) error {
	features := make([]outputFeature, 0, len(outlines))
	for _, outline := range outlines {
		var feature outputFeature
		feature.Type = "Feature"
		feature.Properties.ID = outline.Zone.ID
		feature.Properties.Name = outline.Zone.Name
		feature.Geometry.Type = "MultiPolygon"
		feature.Geometry.Coordinates = outline.Polygons
		features = append(features, feature)
	}
	encoded, err := json.Marshal(struct {
		Type     string          `json:"type"`
		Features []outputFeature `json:"features"`
	}{Type: "FeatureCollection", Features: features})
	if err != nil {
		return err
	}
	source := fmt.Sprintf(generatedSource, "`"+string(encoded)+"`")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(source), 0o644)
}
