package infrastructure

import (
	"fmt"
	"go/format"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

// CountryPointsFile is the path, relative to the back module, of the generated country points.
const CountryPointsFile = "var/geozone/countries.gen.go"

// WriteCountryPoints saves, per country, a point inside it ([longitude, latitude]) as a
// map of the generated Go package.
func WriteCountryPoints(path string, points map[string][2]float64) error {
	var source strings.Builder
	source.WriteString("// Code generated by cmd/zones from Natural Earth. DO NOT EDIT.\n\npackage geozone\n\n")
	source.WriteString("// CountryPoints gives, per country, a point inside it: [longitude, latitude].\n")
	source.WriteString("var CountryPoints = map[string][2]float64{\n")
	for _, country := range slices.Sorted(maps.Keys(points)) {
		point := points[country]
		fmt.Fprintf(&source, "%q: {%s, %s},\n", country, coordinate(point[0]), coordinate(point[1]))
	}
	source.WriteString("}\n")

	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return fmt.Errorf("format country points: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, formatted, 0o644)
}

func coordinate(value float64) string {
	return strconv.FormatFloat(value, 'f', -1, 64)
}
